'use strict';
// Deterministic offline bundle; fail the build rather than silently ship missing languages.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),locales=['en','cs','de','fr','es','it','pl','ru','pt-BR','zh-CN','ja','ko','tr'];
function bundle(){
 const dictionaries={},english=JSON.parse(fs.readFileSync(path.join(root,'src/locales/en.json'),'utf8'));
 const keys=Object.keys(english).sort();
 for(const locale of locales){
  const data=JSON.parse(fs.readFileSync(path.join(root,'src/locales',locale+'.json'),'utf8'));
  if(JSON.stringify(Object.keys(data).sort())!==JSON.stringify(keys))throw Error('Incomplete locale: '+locale);
  for(const key of keys){
   if(typeof data[key]!=='string'||!data[key].trim()||data[key].includes('\ufffd'))throw Error('Invalid translation: '+locale+' '+key);
   const placeholders=value=>JSON.stringify((value.match(/\{\d+\}/g)||[]).sort());
   if(placeholders(key)!==placeholders(data[key]))throw Error('Placeholder mismatch: '+locale+' '+key);
  }
  dictionaries[locale]=Object.fromEntries(keys.map(key=>[key,data[key]]));
 }
 fs.writeFileSync(path.join(root,'src/locales.js'),'// Generated by tools/bundle-locales.cjs. Offline UI dictionaries.\nwindow.KCD2_TRANSLATIONS = '+JSON.stringify(dictionaries)+';\n');
 return {locales:locales.length,keys:keys.length};
}
if(require.main===module)console.log(JSON.stringify(bundle()));
module.exports=bundle;
